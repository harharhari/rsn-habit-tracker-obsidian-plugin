import { readFile, writeFile, mkdir, copyFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
const root = fileURLToPath(new URL("../", import.meta.url));
const read = (name) => readFile(path.join(root, name), "utf8");
const core = await read("src/core.js");
const source = (await read("src/plugin-source.js")).replace(
  'const COLOR_REFERENCE = "";',
  "const COLOR_REFERENCE = " +
    JSON.stringify(await read("hex-color-list.md")) +
    ";",
);
const importPattern = /const C\s*=\s*require\(["']\.\/core["']\);/;
if (!importPattern.test(source))
  throw new Error(
    "Core import not found: update the bundler before releasing.",
  );
const bundle =
  "// SPDX-License-Identifier: GPL-3.0-only\n// Copyright (C) 2026 harharhari\n// Generated by npm run build. Corresponding source is in src/.\n" +
  "const HabitCore = (() => { const module = {exports:{}};\n" +
  core +
  "\nreturn module.exports;})();\n" +
  source.replace(importPattern, "const C = HabitCore;");
await mkdir(path.join(root, "release"), { recursive: true });
await writeFile(path.join(root, "main.js"), bundle);
await writeFile(path.join(root, "release/main.js"), bundle);
for (const name of ["manifest.json", "styles.css", "hex-color-list.md"])
  await copyFile(path.join(root, name), path.join(root, "release", name));
console.log(
  "Built main.js and four loose release assets (including hex-color-list.md).",
);
